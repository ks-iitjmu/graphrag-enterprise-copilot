"""Build the evaluation set: eval/testset.jsonl (about 50 questions).

Categories, each with the tools a correct route needs:
  sql          financial numbers; references computed exactly from finance.db
  cypher       relationships; references computed from the knowledge graph
  vector       text questions generated by the LLM from one specific passage each
               (written to eval/vector_review.csv for MANUAL REVIEW before use)
  combined     need two tools; references computed from the graph and finance.db
  unanswerable the data cannot answer them; a correct answer says so

Graph references test whether the agent retrieves what the graph holds. The graph itself
was built by an LLM, so they do not prove the graph is complete; that limit is stated in
the README. Questions avoid the exact examples used in the prompts.

Usage:  python eval/build_testset.py            (needs Ollama and Neo4j running)
        python eval/build_testset.py --apply-review   after editing eval/vector_review.csv
"""
