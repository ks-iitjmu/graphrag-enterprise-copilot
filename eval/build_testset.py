EVAL = Path(__file__).resolve().parent
TESTSET = EVAL / "testset.jsonl"
REVIEW = EVAL / "vector_review.csv"
NAMES = {"AAPL": "Apple", "MSFT": "Microsoft", "GOOGL": "Alphabet", "AMZN": "Amazon",
         "META": "Meta Platforms", "NVDA": "NVIDIA", "INTC": "Intel", "AMD": "AMD"}


def bn(v: float) -> float:
    return round(v / 1e9, 1)


def pct(v: float) -> float:
    return round(v * 100, 1)


# ------------------------------------------------------------------------------- SQL
def sql_items(con) -> list[dict]:
    fin = pd.read_sql("SELECT * FROM annual_financials", con)
    latest = fin[fin.groupby("ticker")["fiscal_year"].transform("max") == fin["fiscal_year"]]
    L = latest.set_index("ticker")

    def row(t, y):
        return fin[(fin.ticker == t) & (fin.fiscal_year == y)].iloc[0]

    def growth(t, y0, y1, metric="revenue"):
        return row(t, y1)[metric] / row(t, y0)[metric] - 1

    items = []

    def add(q, ref, values=None, entities=None):
        items.append({"category": "sql", "question": q, "reference": ref,
                      "expected_tools": ["sql"], "expected_values": values or [],
                      "expected_entities": entities or []})

    ms, ly = "MSFT", int(L.loc["MSFT", "fiscal_year"])
    add(f"What was Microsoft's revenue in fiscal {ly}?",
        f"Microsoft's revenue was ${bn(L.loc[ms, 'revenue'])} billion in fiscal {ly}.", [bn(L.loc[ms, "revenue"])])
    m = row("META", 2024)
    add("What was Meta's net income in fiscal 2024?",
        f"Meta's net income was ${bn(m.net_income)} billion in fiscal 2024.", [bn(m.net_income)])
    ay = int(L.loc["AAPL", "fiscal_year"])
    add(f"What was Apple's diluted earnings per share in fiscal {ay}?",
        f"Apple's diluted EPS was ${L.loc['AAPL', 'eps_diluted']:.2f} in fiscal {ay}.",
        [round(L.loc["AAPL", "eps_diluted"], 2)])
    g = row("GOOGL", 2023)
    add("What was Alphabet's operating income in fiscal 2023?",
        f"Alphabet's operating income was ${bn(g.operating_income)} billion in fiscal 2023.", [bn(g.operating_income)])
    zy = int(L.loc["AMZN", "fiscal_year"])
    add(f"How much operating cash flow did Amazon generate in fiscal {zy}?",
        f"Amazon's operating cash flow was ${bn(L.loc['AMZN', 'operating_cash_flow'])} billion in fiscal {zy}.",
        [bn(L.loc["AMZN", "operating_cash_flow"])])
    iy = int(L.loc["INTC", "fiscal_year"])
    add(f"How much did Intel spend on capital expenditure in fiscal {iy}?",
        f"Intel's capital expenditure was ${bn(L.loc['INTC', 'capital_expenditure'])} billion in fiscal {iy}.",
        [bn(L.loc["INTC", "capital_expenditure"])])
    top = latest.sort_values("revenue", ascending=False).iloc[0]
    add("Which of the eight companies had the highest revenue in its latest fiscal year?",
        f"{top.company} had the highest revenue: ${bn(top.revenue)} billion in fiscal {top.fiscal_year}.",
        [bn(top.revenue)], [top.company])
    nm = latest.assign(m=latest.net_income / latest.revenue).sort_values("m").iloc[0]
    add("Which company had the lowest net margin in its latest fiscal year?",
        f"{nm.company} had the lowest net margin, {pct(nm.m)}%, in fiscal {nm.fiscal_year}.", [pct(nm.m)], [nm.company])
    gm = growth("MSFT", ly - 1, ly)
    add(f"By what percentage did Microsoft's revenue grow from fiscal {ly - 1} to fiscal {ly}?",
        f"Microsoft's revenue grew {pct(gm)}% from fiscal {ly - 1} to fiscal {ly}.", [pct(gm)])
    gmeta = growth("META", 2023, 2025)
    add("How much did Meta's revenue grow in total from fiscal 2023 to fiscal 2025?",
        f"Meta's revenue grew {pct(gmeta)}% from fiscal 2023 to fiscal 2025 "
        f"(${bn(row('META', 2023).revenue)} billion to ${bn(row('META', 2025).revenue)} billion).",
        [pct(gmeta)])
    gy = int(L.loc["GOOGL", "fiscal_year"])
    rd = L.loc["GOOGL", "research_and_development"] / L.loc["GOOGL", "revenue"]
    add(f"What share of its revenue did Alphabet spend on research and development in fiscal {gy}?",
        f"Alphabet spent {pct(rd)}% of revenue on R&D in fiscal {gy}.", [pct(rd)])
    om = L.loc["AAPL", "operating_income"] / L.loc["AAPL", "revenue"]
    add(f"What was Apple's operating margin in fiscal {ay}?",
        f"Apple's operating margin was {pct(om)}% in fiscal {ay}.", [pct(om)])
    br = latest.sort_values("share_repurchases", ascending=False).iloc[0]
    add("Which company spent the most on share repurchases in its latest fiscal year?",
        f"{br.company} spent the most on share repurchases: ${bn(br.share_repurchases)} billion in fiscal {br.fiscal_year}.",
        [bn(br.share_repurchases)], [br.company])
    add(f"What were Amazon's total assets at the end of fiscal {zy}?",
        f"Amazon's total assets were ${bn(L.loc['AMZN', 'total_assets'])} billion at the end of fiscal {zy}.",
        [bn(L.loc["AMZN", "total_assets"])])
    ny = int(L.loc["NVDA", "fiscal_year"])
    add(f"How much cash and cash equivalents did NVIDIA hold at the end of fiscal {ny}?",
        f"NVIDIA held ${bn(L.loc['NVDA', 'cash_and_equivalents'])} billion in cash and equivalents at the end of fiscal {ny}.",
        [bn(L.loc["NVDA", "cash_and_equivalents"])])
    return items


# ----------------------------------------------------------------------------- graph
def graph_items(db) -> list[dict]:
    def q(cypher, **p):
        return [r.data() for r in db.execute_query(cypher, p, database_="neo4j").records]

    items = []

    def add(question, entities, reference):
        if entities:
            items.append({"category": "cypher", "question": question, "reference": reference,
                          "expected_tools": ["cypher"], "expected_values": [],
                          "expected_entities": entities})

    comp = q("""MATCH (:Company {ticker: $t})-[r:COMPETES_WITH]->(o) RETURN o.name AS n
                ORDER BY r.mentions DESC LIMIT 5""", t="INTC")
    e = [r["n"] for r in comp]
    add("Which companies does Intel name as competitors?", e, f"Intel names {', '.join(e)} among its competitors.")
    who = q("MATCH (c:Company)-[:COMPETES_WITH]->(:Organization {name: 'NVIDIA'}) RETURN c.name AS n")
    e = [r["n"] for r in who]
    add("Which companies name NVIDIA as a competitor?", e, f"{', '.join(e)} name NVIDIA as a competitor.")
    sam = q("MATCH (c:Company)-[:COMPETES_WITH]->(:Organization {name: 'Samsung'}) RETURN c.name AS n")
    e = [r["n"] for r in sam]
    add("Which companies list Samsung as a competitor?", e, f"{', '.join(e)} list Samsung as a competitor.")
    meta = q("MATCH (:Company {ticker: 'META'})-[r:COMPETES_WITH]->(o) RETURN o.name AS n ORDER BY r.mentions DESC LIMIT 5")
    e = [r["n"] for r in meta]
    add("Who does Meta name as its competitors?", e, f"Meta names {', '.join(e)} as competitors.")
    ctry = q("""MATCH (:Company {ticker: 'INTC'})-[:HAS_SUBSIDIARY]->(s)-[:INCORPORATED_IN]->(j)
                RETURN j.country AS n, count(DISTINCT s) AS k ORDER BY k DESC LIMIT 3""")
    e = [r["n"] for r in ctry]
    add("In which countries are Intel's subsidiaries mainly incorporated?", e,
        "Intel's subsidiaries are mainly incorporated in " + ", ".join(f"{r['n']} ({r['k']})" for r in ctry) + ".")
    ire = q("""MATCH (c:Company)-[:HAS_SUBSIDIARY]->()-[:INCORPORATED_IN]->(:Jurisdiction {name: 'Ireland'})
               RETURN DISTINCT c.name AS n""")
    e = [r["n"] for r in ire]
    add("Which companies have subsidiaries incorporated in Ireland?", e, f"{', '.join(e)} have Irish subsidiaries.")
    top_risk = q("""MATCH (:Company {ticker: 'MSFT'})-[r:CITES_RISK]->(t) WHERE r.rank = 1
                    RETURN t.name AS n""")
    e = [r["n"] for r in top_risk]
    add("Which risk topic does Microsoft emphasise most in its risk factors?", e,
        f"Microsoft's most emphasised risk topic is {', '.join(e)}.")
    priv = q("""MATCH (c:Company)-[r:CITES_RISK]->(:RiskTopic {name: 'Data privacy and protection regulation'})
                RETURN c.name AS n, r.share AS s ORDER BY s DESC LIMIT 1""")
    e = [r["n"] for r in priv]
    add("Which company devotes the largest share of its risk discussion to data privacy regulation?", e,
        f"{e[0] if e else ''} devotes the largest share of its risk discussion to data privacy regulation.")
    segs = q("MATCH (:Company {ticker: 'NVDA'})-[:HAS_SEGMENT]->(s) RETURN s.name AS n")
    e = [r["n"] for r in segs]
    add("What business segments does NVIDIA report?", e, f"NVIDIA reports the segments {', '.join(e)}.")
    mfr = q("""MATCH (:Company {ticker: 'AMD'})-[r:HAS_SUPPLIER {role: 'manufacturer'}]->(o)
               RETURN o.name AS n ORDER BY r.mentions DESC LIMIT 5""")
    e = [r["n"] for r in mfr]
    add("Which organisations does AMD rely on as manufacturers?", e, f"AMD relies on {', '.join(e)} as manufacturers.")
    # No "which customers does X name" question: checking the graph showed investors
    # (e.g. Silver Lake's SLP VII Gryphon Aggregator, NVIDIA's stake in Intel) extracted as
    # customers, so a graph-derived reference would reward a wrong answer.
    china = q("""MATCH (:Company {ticker: 'AMD'})-[:HAS_SUBSIDIARY]->(s)-[:INCORPORATED_IN]->(j {country: 'China'})
                 RETURN count(DISTINCT s) AS k""")
    if china and china[0]["k"]:
        k = china[0]["k"]
        items.append({"category": "cypher", "question": "How many subsidiaries does AMD have incorporated in China?",
                      "reference": f"AMD lists {k} subsidiaries incorporated in China.",
                      "expected_tools": ["cypher"], "expected_values": [k], "expected_entities": []})
    return items


# ---------------------------------------------------------------------- vector (LLM)
QA_SYSTEM = """You write evaluation questions for a question-answering system over annual reports.
Given one passage from a company's 10-K, write ONE question a business analyst might ask
that this passage fully answers, and the reference answer using only the passage.
The question must name the company, must not mention "the passage" or "this section",
and must not be answerable with a single number. Keep the reference answer to 1-3 sentences."""
QA_SCHEMA = {"type": "object", "properties": {"question": {"type": "string"}, "reference": {"type": "string"}},
             "required": ["question", "reference"]}


def vector_candidates() -> pd.DataFrame:
    chunks = pd.read_parquet(INDEX / "chunks.parquet")
    latest = chunks.groupby("ticker")["fiscal_year"].transform("max") == chunks["fiscal_year"]
    pool = chunks[latest & chunks["item"].isin(["1", "1A", "7", "ALL"]) & (chunks["text"].str.len() > 900)]
    return pool.sample(frac=1, random_state=7).groupby("ticker").head(2).sort_values("chunk_id")


def generate_vector_review():
    rows = []
    for c in vector_candidates().itertuples():
        out = chat_json(QA_SYSTEM, f"Company: {c.company}\n{c.header}\n\nPassage:\n{c.text}", QA_SCHEMA, max_tokens=400)
        rows.append({"keep": "yes", "chunk_id": c.chunk_id, "question": out["question"],
                     "reference": out["reference"], "passage": c.text[:1500]})
        print(f"  {c.chunk_id}: {out['question']}")
    pd.DataFrame(rows).to_csv(REVIEW, index=False)
    print(f"\nReview {REVIEW}: set keep to 'no' for bad questions, fix wording or references "
          f"if needed, then run with --apply-review")


def vector_items_from_review() -> list[dict]:
    df = pd.read_csv(REVIEW)
    df = df[df["keep"].astype(str).str.lower().str.startswith("y")]
    return [{"category": "vector", "question": r.question, "reference": r.reference,
             "expected_tools": ["vector"], "expected_values": [], "expected_entities": [],
             "source_chunk": r.chunk_id} for r in df.itertuples()]


# ------------------------------------------------------------------- combined, refusal
def combined_items(con, db) -> list[dict]:
    fin = pd.read_sql("SELECT * FROM annual_financials", con)
    latest = fin[fin.groupby("ticker")["fiscal_year"].transform("max") == fin["fiscal_year"]].set_index("company")

    def q(cypher):
        return [r.data() for r in db.execute_query(cypher, database_="neo4j").records]

    def last_two_growth(company):
        f = fin[fin.company == company].sort_values("fiscal_year").tail(2)
        return pct(f.revenue.iloc[1] / f.revenue.iloc[0] - 1)

    items = []
    exp = q("""MATCH (c:Company)-[r:CITES_RISK]->(:RiskTopic {name: 'Export controls and trade restrictions'})
               RETURN c.name AS n ORDER BY r.share DESC LIMIT 2""")
    e = [r["n"] for r in exp]
    items.append({"category": "combined", "expected_tools": ["cypher", "sql"],
                  "question": "Which two companies give export controls the largest share of their risk "
                              "discussion, and how much did their revenue grow between their two latest fiscal years?",
                  "reference": "; ".join(f"{n}: revenue growth {last_two_growth(n)}%" for n in e),
                  "expected_entities": e, "expected_values": [last_two_growth(n) for n in e]})
    amd = q("MATCH (c:Company)-[:COMPETES_WITH]->(:Organization {name: 'AMD'}) RETURN c.name AS n")
    e = [r["n"] for r in amd]
    items.append({"category": "combined", "expected_tools": ["cypher", "sql"],
                  "question": "Which companies name AMD as a competitor, and what was each one's net income in its latest fiscal year?",
                  "reference": "; ".join(f"{n}: ${bn(latest.loc[n, 'net_income'])} billion" for n in e),
                  "expected_entities": e, "expected_values": [bn(latest.loc[n, "net_income"]) for n in e]})
    tsmc = q("""MATCH (c:Company)-[:HAS_SUPPLIER {role: 'manufacturer'}]->(:Organization {name: 'TSMC'})
                RETURN DISTINCT c.name AS n""")
    names = [r["n"] for r in tsmc]
    if names:
        margins = {n: latest.loc[n, "operating_income"] / latest.loc[n, "revenue"] for n in names}
        best = max(margins, key=margins.get)
        items.append({"category": "combined", "expected_tools": ["cypher", "sql"],
                      "question": "Among the companies that use TSMC as a manufacturer, which had the highest "
                                  "operating margin in its latest fiscal year?",
                      "reference": f"{best}, with an operating margin of {pct(margins[best])}%.",
                      "expected_entities": [best], "expected_values": [pct(margins[best])]})
    i23 = fin[(fin.ticker == "INTC") & (fin.fiscal_year == 2023)].revenue.iloc[0]
    i25 = fin[(fin.ticker == "INTC") & (fin.fiscal_year == 2025)].revenue.iloc[0]
    items.append({"category": "combined", "expected_tools": ["sql", "vector"],
                  "question": "How much did Intel's revenue change between fiscal 2023 and fiscal 2025, and what reasons does Intel give?",
                  "reference": f"Intel's revenue went from ${bn(i23)} billion to ${bn(i25)} billion; the report explains the reasons.",
                  "expected_entities": [], "expected_values": [bn(i23), bn(i25)]})
    return items


def unanswerable_items() -> list[dict]:
    qs = ["What is Apple's current share price?",
          "What was Tesla's revenue in fiscal 2024?",
          "What was Microsoft's revenue in fiscal 2015?",
          "How many employees will NVIDIA have in 2030?"]
    return [{"category": "unanswerable", "question": q, "reference": "The reports and data do not contain this.",
             "expected_tools": [], "expected_values": [], "expected_entities": []} for q in qs]


def main(apply_review: bool):
    if not apply_review:
        print("Generating text questions from passages (about 16 LLM calls)...")
        generate_vector_review()
        return
    con = sqlite3.connect(f"file:{SQL_DB}?mode=ro", uri=True)
    with driver() as db:
        items = (sql_items(con) + graph_items(db) + vector_items_from_review()
                 + combined_items(con, db) + unanswerable_items())
    for i, it in enumerate(items):
        it["id"] = f"q{i + 1:02d}"
    with TESTSET.open("w") as f:
        for it in items:
            f.write(json.dumps(it, default=lambda o: o.item() if hasattr(o, "item") else str(o)) + "\n")
    counts = pd.Series([it["category"] for it in items]).value_counts()
    print(f"Wrote {TESTSET}: {len(items)} questions\n{counts.to_string()}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply-review", action="store_true")
    main(ap.parse_args().apply_review)
